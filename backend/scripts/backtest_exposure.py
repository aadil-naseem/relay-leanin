"""M4 back-test: score the Michaung replay over known flooded vs not-flooded sites.

This is a *report* (Phase 7 task 6), not just a pass/fail test: it prints a
ranking table and writes `docs/BACKTEST_EXPOSURE.md`. The assertion is only
"flooded sites rank above not-flooded ones" - and if that fails, the fix is to
tune weights in config/exposure.yaml, never to special-case a site name.

Usage: python scripts/backtest_exposure.py
"""

from __future__ import annotations

import sys
from datetime import datetime, timezone
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND_DIR))

from sqlalchemy import select  # noqa: E402
from sqlalchemy.orm import Session  # noqa: E402

from app.adapters import weather  # noqa: E402
from app.config_loader import load_configs  # noqa: E402
from app.core import exposure_score  # noqa: E402
from app.db import engine  # noqa: E402
from app.models import SiteTerrain  # noqa: E402

DOCS_DIR = BACKEND_DIR.parent / "docs"


def main() -> int:
    bundle = load_configs()
    cfg = bundle.exposure

    flooded = [site.id for site in bundle.cluster.backtest_flooded]
    all_sites = {site.id: site for site in bundle.cluster.backtest_flooded + bundle.cluster.backtest_not_flooded}

    with Session(engine) as session:
        terrain = {row.site_id: row for row in session.scalars(select(SiteTerrain)).all()}
        specs = [
            weather.SiteSpec(site_id=site_id, lat=site.lat, lon=site.lon)
            for site_id, site in all_sites.items()
        ]
        result = weather.get_hourly_precip(session, specs, "replay")

        rows = []
        for site_id, site in all_sites.items():
            row = terrain.get(site_id)
            series = list(result.series(site_id))
            rain = exposure_score.rain_hazard(series, cfg)
            vuln = exposure_score.vulnerability(
                elevation_m=row.elevation_m if row else 0.0,
                ring_mean_m=row.ring_mean_m if row else 0.0,
                nearest_water_m=row.nearest_water_m if row else None,
                zone_ids=list(row.zone_ids or []) if row else [],
                cfg=cfg,
            )
            risk = exposure_score.site_risk(rain.hazard, vuln, cfg)
            rows.append(
                {
                    "site_id": site_id,
                    "name": site.name,
                    "flooded": site_id in flooded,
                    "risk": risk,
                    "hazard": rain.hazard,
                    "max24": rain.max24_mm,
                    "vuln": vuln.value,
                    "depression": vuln.depression,
                    "water": vuln.water_proximity,
                    "zone": vuln.flood_history,
                }
            )

    rows.sort(key=lambda row: -row["risk"])

    print(f"\nM4 back-test - Cyclone Michaung replay (mode=replay, source={result.source})\n")
    header = f"{'site':22s} {'truth':10s} {'risk':>5s} {'H':>5s} {'24h mm':>8s} {'V':>5s} {'D':>5s} {'W':>5s} {'Z':>3s}"
    print(header)
    print("-" * len(header))
    for row in rows:
        truth = "FLOODED" if row["flooded"] else "not flooded"
        print(
            f"{row['name'][:22]:22s} {truth:10s} {row['risk']:5d} {row['hazard']:5.2f} "
            f"{row['max24']:8.1f} {row['vuln']:5.2f} {row['depression']:5.2f} {row['water']:5.2f} {row['zone']:3.0f}"
        )

    separator = min(row["risk"] for row in rows if row["flooded"]) - max(
        row["risk"] for row in rows if not row["flooded"]
    )
    passed = separator > 0
    print(f"\nlowest flooded risk - highest not-flooded risk = {separator:+d}")
    print("PASS: every flooded site ranks above every not-flooded site." if passed else "FAIL: bands overlap.")

    lines = [
        "# M4 exposure back-test - Cyclone Michaung (Dec 2023)",
        "",
        "Generated by `backend/scripts/backtest_exposure.py` in `replay` mode.",
        "Weather: Open-Meteo archive, real hourly precipitation. Terrain: Open-Meteo elevation.",
        "Zones: curated planning circles from public reporting, **not** official flood maps.",
        "Risk is a **risk indicator, not a flood model**.",
        "",
        f"Generated (UTC): {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        "",
        "| Site | Truth | Risk | H (rain) | 24 h mm | V | Depression | Water | Zone |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        truth = "FLOODED" if row["flooded"] else "not flooded"
        lines.append(
            f"| {row['name']} | {truth} | **{row['risk']}** | {row['hazard']:.2f} | {row['max24']:.1f} | "
            f"{row['vuln']:.2f} | {row['depression']:.2f} | {row['water']:.2f} | {row['zone']:.0f} |"
        )
    lines += [
        "",
        f"Separation (lowest flooded - highest not-flooded): **{separator:+d} points**.",
        "",
        "Result: **PASS** - every flooded site ranks above every not-flooded site." if passed
        else "Result: **FAIL** - bands overlap; tune weights in config/exposure.yaml, not code.",
        "",
        "## Sources for the flood labels",
        "",
        "- Ambattur north phase: KNN India 2023-12-07 (north phase water); The Hindu 2023-12-04.",
        "- Villivakkam / Thirumudivakkam / Perungudi: The Week 2023-12-06 (4-6 ft water);",
        "  The Hindu Businessline 2023-12-08 (flooding crippled MSME units in these estates).",
        "- Oragadam / Irungattukottai / Pillaipakkam (not flooded): Deccan Herald 2023-12",
        "  (Tamil Nadu government: Oragadam situation 'was better', industrial parks resumed).",
        "",
    ]
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    out = DOCS_DIR / "BACKTEST_EXPOSURE.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())